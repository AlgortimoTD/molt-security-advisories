#!/usr/bin/env node
// Builds feed.json, the single file consumers fetch. Deterministic: the same records always
// produce the same bytes, so CI can check the committed feed with --check.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, readJson, recordFiles } from './lib.mjs';
import { validateAll } from './validate.mjs';

export function buildFeed(root = ROOT) {
  const advisories = [], rejected = [];
  for (const { file, dir } of recordFiles(root)) {
    const record = readJson(file);
    if (dir === 'advisories') advisories.push(record);
    else rejected.push({ id: record.id, claim: record.claim, verdict: record.verdict, published: record.published, updated: record.updated, related: record.related ?? [], url: `https://github.com/AlgortimoTD/molt-security-advisories/blob/main/rejected/${record.id.slice(4, 8)}/${record.id}.json` });
  }
  const byId = (a, b) => a.id.localeCompare(b.id);
  advisories.sort(byId); rejected.sort(byId);
  const updated = [...advisories, ...rejected].map(r => r.updated).sort().at(-1) ?? null;
  return {
    schema: 'msa-feed/1',
    publisher: 'MOLT Security Advisories',
    homepage: 'https://github.com/AlgortimoTD/molt-security-advisories',
    updated,
    advisories,
    rejected,
  };
}

export const serialize = feed => `${JSON.stringify(feed, null, 2)}\n`;

// The README opens with the most recent publication days, so a reader landing on the repository
// sees what changed lately. The window counts publication days present in the records, never the
// clock, so the same records always render the same README and --check stays stable.
export const LATEST_DAYS = 3;
export const README_START = '<!-- latest-advisories:start (generated by npm run feed; do not edit by hand) -->';
export const README_END = '<!-- latest-advisories:end -->';
const LEVELS = ['critical', 'high', 'medium', 'low', 'informational'];
const URGENCY = { '24h': '24 hours', '72h': '72 hours', '30d': '30 days', 'next-update': 'Next update' };
const capital = text => text.charAt(0).toUpperCase() + text.slice(1);
// Table cells come from record text, which can quote external sources: render it as plain text.
// One line, Markdown punctuation escaped (no links, images, emphasis or column splits) and HTML
// escaped (nothing renders, and a copied section marker cannot break the section).
const cell = text => String(text).replace(/\s+/g, ' ').trim().replace(/[\\`*_{}[\]()#+!|~-]/g, '\\$&')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const recordPath = (dir, id) => `${dir}/${id.slice(4, 8)}/${id}.json`;

export function renderLatest(feed, days = LATEST_DAYS) {
  // A record appears on its publication day and, when corrected later, again on its update day.
  const appearances = (record, row) => [{ ...row, day: record.published, label: '' },
    ...(record.updated && record.updated !== record.published ? [{ ...row, day: record.updated, label: ' (updated)' }] : [])];
  const rows = [
    ...feed.advisories.flatMap(a => {
      const exploited = a.exploitation?.status === 'exploited-in-the-wild' ? ', exploited in the wild' : '';
      const severity = a.status === 'withdrawn' ? 'Withdrawn' : `${capital(a.severity.level)}${exploited}`;
      const act = a.status === 'withdrawn' ? '' : URGENCY[a.severity.urgency];
      return appearances(a, { rank: a.status === 'withdrawn' ? LEVELS.length : LEVELS.indexOf(a.severity.level), id: a.id,
        link: `[${a.id}](${recordPath('advisories', a.id)})`, rest: `| ${severity} | ${act} | ${cell(a.title)} |` });
    }),
    ...feed.rejected.flatMap(r => appearances(r, { rank: LEVELS.length + 1, id: r.id,
      link: `[${r.id}](${recordPath('rejected', r.id)})`, rest: `| Rejected claim: ${r.verdict} |  | ${cell(r.claim)} |` })),
  ].map(r => ({ ...r, text: `| ${r.link}${r.label} ${r.rest}` }));
  const recent = [...new Set(rows.map(r => r.day))].sort().reverse().slice(0, days);
  const lines = [README_START, `The ${days} most recent publication days, newest first. Every record is in [\`feed.json\`](feed.json).`, ''];
  if (!recent.length) lines.push('No records published yet.', '');
  for (const day of recent) {
    lines.push(`### ${day}`, '', '| Record | Severity | Act within | What it is |', '| --- | --- | --- | --- |');
    rows.filter(r => r.day === day).sort((a, b) => a.rank - b.rank || a.id.localeCompare(b.id)).forEach(r => lines.push(r.text));
    lines.push('');
  }
  lines.push(README_END);
  return lines.join('\n');
}

/** Replaces the generated section of the README; fails closed when its markers are missing. */
export function updateReadme(text, feed) {
  const start = text.indexOf(README_START), end = text.indexOf(README_END);
  const once = marker => text.split(marker).length === 2;
  if (!once(README_START) || !once(README_END) || end < start) throw Error('README.md needs exactly one latest-advisories section between its markers.');
  return text.slice(0, start) + renderLatest(feed) + text.slice(end + README_END.length);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { problems } = validateAll();
  if (problems.length) { console.error('Records are not valid; run npm run validate.'); process.exit(1); }
  const feed = buildFeed(), target = path.join(ROOT, 'feed.json'), next = serialize(feed);
  const readme = path.join(ROOT, 'README.md'), currentReadme = fs.readFileSync(readme, 'utf8');
  let nextReadme;
  try { nextReadme = updateReadme(currentReadme, feed); } catch (error) { console.error(error.message); process.exit(1); }
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    const stale = [current !== next && 'feed.json', currentReadme !== nextReadme && 'README.md'].filter(Boolean);
    if (stale.length) { console.error(`${stale.join(' and ')} out of date; run npm run feed and commit it.`); process.exit(1); }
    console.log('feed.json and README.md are up to date.');
  } else {
    fs.writeFileSync(target, next);
    fs.writeFileSync(readme, nextReadme);
    console.log(`feed.json written (${feed.advisories.length} advisories); README.md latest section updated.`);
  }
}
